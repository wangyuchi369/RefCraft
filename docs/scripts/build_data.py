#!/usr/bin/env python3
"""Build the checked-in, file://-compatible data bundle. No network or model calls."""
import json
import base64
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    read = lambda name: json.loads((ROOT / "data" / name).read_text())
    payload = {
        "config": read("config.json"),
        "authors": read("authors.json"),
        "examples": read("examples.json"),
        "models": read("leaderboard.json"),
        "domains": [
            {"name": name, "count": count} for name, count in [
                ("Content / media", 53), ("Commerce", 41), ("Organizations", 41),
                ("Branding", 39), ("Events / community", 38), ("Data / monitoring", 31),
                ("Tools / apps", 29), ("Personal / portfolio", 28),
            ]
        ],
        "abstract": "Beyond basic tool use and coding skills, effectively incorporating visual references into agentic generation is equally essential for applying AI agents to real-world productivity tasks. We study this crucial capability through webpage development, a practical and readily evaluable setting in which existing benchmarks remain largely idealized: they typically focus on reconstructing visual targets or generating webpages from textual instructions alone, overlooking the more common workflow of developing from visual examples. Specifically, we introduce RefCraft, a benchmark comprising 300 realistic multimodal webpage-development tasks that combine natural-language instructions with screenshots from one to five reference webpages. Agents must selectively interpret and utilize these references while rendering, visually inspecting, and iteratively refining their outputs. We evaluate the resulting open-ended artifacts using independently verifiable keypoints and complementary programmatic and VLM judges. Across nine frontier (M)LLMs, the strongest system achieves an overall score of only 52.12 out of 100, revealing that visual-reference-conditioned agentic generation remains a substantial challenge for current models in practical webpage-development settings.",
    }
    assert len(payload["models"]) == 9
    assert sum(item["count"] for item in payload["domains"]) == 300
    # Model marks travel as data URIs so the plot's SVG and the standalone file
    # both work without a separate image request. Source: scripts/extract_model_marks.py.
    for model in payload["models"]:
        mark = ROOT / "assets" / "brands" / "marks" / f"{model['logo']}.png"
        assert mark.is_file(), f"{model['name']}: missing mark {mark.name}"
        model["mark"] = "data:image/png;base64," + base64.b64encode(mark.read_bytes()).decode("ascii")
    for case in payload["examples"]:
        for image in [*case["references"], case["output"]]:
            assert (ROOT / image["src"]).is_file(), image["src"]
        demo_path = f"demos/task-{case['id']:03d}.html"
        demo_bytes = (ROOT / demo_path).read_bytes()
        score = case.get("score")
        if score:
            assert score["htmlSha256"] == hashlib.sha256(demo_bytes).hexdigest(), f"Task {case['id']}: score belongs to another HTML"
            assert all(0 <= score[key] <= 100 for key in ["overall", "b", "c", "r"])
            assert abs(score["overall"] - min(score["b"], score["c"], score["r"])) < 1e-8
        case["demo"] = {
            "src": demo_path,
            "base64": base64.b64encode(demo_bytes).decode("ascii"),
            "sha256": hashlib.sha256(demo_bytes).hexdigest(),
        }
    bundle = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    (ROOT / "data/site-data.js").write_text("// Generated by scripts/build_data.py. Edit the JSON source files.\nwindow.REFCRAFT = " + bundle + ";\n")
    print(f"Built {len(payload['examples'])} cases, {len(payload['models'])} models, and 8 domains.")


if __name__ == "__main__":
    build()
